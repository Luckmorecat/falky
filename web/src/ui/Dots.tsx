/** The letter a name's dot monogram shows; a mark without a shape shows a ring. */
export function monogram(name: string): string {
  const first = [...name.trim()][0]?.toUpperCase() ?? '';
  return GLYPHS[first] ? first : 'O';
}

/** Text drawn in round dots. Only digits, a clock's colon and monograms use it. */
export const Dots = memo(function Dots({ text, label, className }: { text: string; label?: string; className?: string }) {
  const circles: { x: number; y: number }[] = [];
  let x = 0;
  for (const ch of text) {
    const rows = (GLYPHS[ch] ?? GLYPHS.O!).split(' ');
    rows.forEach((row, y) => [...row].forEach((v, i) => {
      if (v === '1') circles.push({ x: x + i + 0.5, y: y + 0.5 });
    }));
    x += rows[0]!.length + 1;
  }
  return (
    <svg className={className} viewBox={`0 0 ${Math.max(1, x - 1)} 7`} fill="#fff" {...(label ? { role: 'img', 'aria-label': label } : { 'aria-hidden': true })}>
      {circles.map((c) => <circle key={`${c.x}-${c.y}`} cx={c.x} cy={c.y} r=".36" />)}
    </svg>
  );
});
