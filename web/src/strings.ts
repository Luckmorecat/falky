export type Language = 'uk' | 'en';
export type LanguageChoice = Language | 'system';

/** English for a system that prefers it, Ukrainian for any other. */
export function systemLanguage(preferred: readonly string[] = navigator.languages): Language {
  return preferred[0]?.toLowerCase().startsWith('en') ? 'en' : 'uk';
}

export const resolveLanguage = (choice: LanguageChoice): Language => (choice === 'system' ? systemLanguage() : choice);

