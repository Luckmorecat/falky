use crate::ui_contract::Language;

macro_rules! catalog {
    ($($key:ident => $en:literal, $uk:literal;)*) => {
        #[derive(Clone, Copy, Debug, Eq, PartialEq)]
        pub enum Key { $($key,)* }

        pub const fn text(language: Language, key: Key) -> &'static str {
            match (language, key) {
                $((Language::En, Key::$key) => $en,
                (Language::Uk, Key::$key) => $uk,)*
            }
        }
    };
}

